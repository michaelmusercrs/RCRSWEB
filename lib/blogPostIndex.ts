// Utility functions (metadata-only, no content loading)
export function getBlogPostMeta(slug: string): BlogPostMeta | undefined {
  return blogPostIndex.find(post => post.slug === slug);
}

export function getAllBlogSlugs(): string[] {
  return blogPostIndex.map(post => post.slug);
}

export function getRecentPostsMeta(count: number = 5): BlogPostMeta[] {
  return [...blogPostIndex].reverse().slice(0, count);
}

export function getPostsByAuthorMeta(author: string): BlogPostMeta[] {
  return blogPostIndex.filter(post => post.author === author);
}
